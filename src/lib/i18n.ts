export type MessageKey = keyof typeof messages.zh;

export function t(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>,
) {
  let text: string = messages[locale][key] ?? messages.zh[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}
